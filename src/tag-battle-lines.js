// K-14(2026-09-25): 勝者セリフは口調×性格の2本(うち1本は {partner} で相手を呼ぶ)と口調別の名前なし3本から
// 等確率で引く(名前を呼ぶ行が出るのは5回に1回)。partnerCallName は**表示言語の呼び名**(呼び名の仕組みが
// 決める。観戦画面には絆が無いので親の app.js が決めて渡す)。空なら名前入りの行を出さない({partner} を生で出さない)。
// 辞書は差し込みの**前**のテンプレに掛けて返す(_tplTagLine)。呼び出し側は戻り値を t() で包み直さない。
// 乱数は表示専用の文選びなので Math.random()(CLAUDE.md 原則4・C-2裁定)。
function pickTagWinLine(fighter, partnerCallName, dict) {
  const archetype = (fighter && fighter.archetype) || 'standard';
  const byCell = _tagLineArrFor(TAG_MATCH_WIN_LINES, fighter) || [];
  const byArch = TAG_MATCH_WIN_NAMELESS_LINES[archetype] || TAG_MATCH_WIN_NAMELESS_LINES.standard;
  let pool = byCell.concat(byArch);
  if (!partnerCallName) pool = pool.filter((line) => line.indexOf('{partner}') < 0);
  const line = pool[Math.floor(Math.random() * pool.length)];
  return _tplTagLine(line, { partner: partnerCallName || '' }, dict);
}
function pickTagLossLine(fighter, partnerName, dict) {
  const arr = _tagLineArrFor(TAG_MATCH_LOSS_LINES, fighter);
  const line = arr[Math.floor(Math.random() * arr.length)];
  // i18n P7-33: partnerName未提供時のフォールバック語は名前辞書に無い一般名詞なので、
  // t()のパラメータ値自動変換(名前/技名のみ対象)では訳せない。dictで直接引く。
  const T = (typeof dict === 'function') ? dict : (s) => s;
  return _tplTagLine(line, { partner: partnerName || T('パートナー') }, dict);
}
function pickTagWinCommentary(winnerName, partnerName, moveName, dict) {
  const arr = TAG_MATCH_COMMENTARY_WIN_LINES;
  const line = arr[Math.floor(Math.random() * arr.length)];
  const T = (typeof dict === 'function') ? dict : (s) => s;
  return _tplTagLine(line, { winner: winnerName || T('勝者'), partner: partnerName || T('パートナー'), move: moveName || T('決め技') }, dict);
}

