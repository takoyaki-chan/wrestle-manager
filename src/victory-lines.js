const SIGNING_TRAIT_PRIORITY = [
  '野心', '破天荒', 'ムードメーカー', '威圧感',
  '華', '努力家', '闘志', 'ファンサービス', '忠誠心',
  '負けず嫌い', '適応力'
];

function getTraitSigningLine(traits, context) {
  if (!traits || !traits.length) return null;
  for (const trait of SIGNING_TRAIT_PRIORITY) {
    if (!traits.includes(trait)) continue;
    const cfg = SIGNING_TRAIT_LINES[trait];
    if (!cfg) continue;
    // contexts === null means all contexts; otherwise must match
    if (cfg.contexts && !cfg.contexts.includes(context)) continue;
    return cfg.lines[Math.floor(Math.random() * cfg.lines.length)];
  }
  return null;
}

function getSigningLine(fighter, context) {
  // Step 1: trait lines (50% chance)
  if (Math.random() < 0.50) {
    const traitLine = getTraitSigningLine(fighter.traits, context);
    if (traitLine) return traitLine;
  }
  // Step 2: generic table by role × context × ageGroup
  const ageGroup = (fighter.age <= 17) ? 'young'
                 : (fighter.age <= 22) ? 'standard'
                 : 'mature';
  const role = (fighter.role || 'Neutral').toLowerCase();
  const pool = SCOUT_SIGNING_LINES[role]?.[context]?.[ageGroup]
            || SCOUT_SIGNING_LINES.neutral.direct.standard;
  return pool[Math.floor(Math.random() * pool.length)];
}

